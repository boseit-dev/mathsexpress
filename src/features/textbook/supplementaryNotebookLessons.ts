import type { NotebookLesson, NotebookQuestion } from './notebookLessons';

/**
 * Original MathsExpress concept introductions for additional NSW K–10 focus areas.
 * The examples are educational starting points, not a mapping of every NESA
 * content point or a claim that the full focus area is finished.
 */
type Q = readonly [prompt: string, answer: number, hint: string, explanation: string];

function makeQuestion([prompt, answer, hint, explanation]: Q): NotebookQuestion {
  return { prompt, answer, hint, explanation };
}

function build(
  books: readonly string[],
  chapterId: string,
  title: string,
  concept: string,
  visual: string,
  principle: string,
  example: string,
  steps: readonly string[],
  guided: Q,
  practice: readonly [Q, Q],
  recap: readonly [string, string, string],
): NotebookLesson[] {
  return books.map((bookId) => ({
    bookId,
    chapterId,
    title,
    concept,
    visual,
    principle,
    example,
    steps,
    guided: makeQuestion(guided),
    practice: practice.map(makeQuestion),
    recap,
  }));
}

