import type { NotebookLesson, NotebookQuestion } from './notebookLessons';

/** Original Stage 6 introductory teaching examples for NSW Mathematics (2024).
 * These introduce the listed focus areas, not every official syllabus outcome.
 * Life Skills examples are optional and require individual teacher selection.
 */
type Q = readonly [prompt: string, answer: number, hint: string, explanation: string];

function item([prompt, answer, hint, explanation]: Q): NotebookQuestion {
  return { prompt, answer, hint, explanation };
}

function teach(
  books: readonly string[], chapterId: string, title: string, concept: string,
  visual: string, principle: string, example: string, steps: readonly string[],
  guided: Q, practice: readonly [Q, Q], recap: readonly [string, string, string],
): NotebookLesson[] {
  return books.map((bookId) => ({
    bookId, chapterId, title, concept, visual, principle, example, steps,
    guided: item(guided), practice: practice.map(item), recap,
  }));
}

